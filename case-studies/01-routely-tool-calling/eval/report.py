"""Render the results table across all eval/scores/*.json (+ error taxonomy appendix).

Usage:
  uv run python eval/report.py [--scores-dir eval/scores] [--out eval/report.md]

Scores from the mock adapter are flagged "(mock) - pipeline test only" and must not be
presented as measured model performance.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]


def fmt(v):
    return "-" if v is None else f"{v}"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scores-dir", default=str(ROOT / "eval" / "scores"))
    ap.add_argument("--out", default=str(ROOT / "eval" / "report.md"))
    args = ap.parse_args(argv)

    scores = []
    for p in sorted(Path(args.scores_dir).glob("*.json")):
        scores.append(json.loads(p.read_text(encoding="utf-8")))
    if not scores:
        print("no score files found - run eval/score.py first")
        return 1
    scores.sort(key=lambda s: -(s.get("response_accuracy") or 0))

    test_hash = ""
    sha_path = ROOT / "data" / "splits" / "sha256.txt"
    if sha_path.exists():
        for line in sha_path.read_text(encoding="utf-8").splitlines():
            if line.strip().endswith("test.jsonl"):
                test_hash = line.split()[0]

    header = ("| Model | Adapter | Overall | clear | confusable | rel.date | multilingual | "
              "no_tool | clarify | Tool sel. | Args full | Parse % | p95 ms |")
    sep = "|" + "---|" * 13
    lines = [f"<!-- generated by eval/report.py; test split sha256: {test_hash} -->", "",
             header, sep]
    for s in scores:
        b = s["by_bucket"]
        name = s["model"] + (" (mock)" if s["adapter"] == "mock" else "")
        lines.append(
            f"| {name} | {s['adapter']} | **{fmt(s['response_accuracy'])}%** | "
            + " | ".join(fmt(b.get(k, {}).get("acc"))
                         for k in ["clear", "confusable", "relative_date", "multilingual",
                                   "no_tool", "clarify"])
            + f" | {fmt(s['tool_selection']['acc'])}% | {fmt(s['args']['full_match_given_tool'])}%"
            + f" | {fmt(s['parse_validity'])}% | {fmt(s['latency_ms']['p95'])} |")
    lines.append("")

    lines.append("## Error taxonomy")
    lines.append("")
    for s in scores:
        errs = ", ".join(f"{k}={v}" for k, v in s["taxonomy"].items() if k != "correct")
        lines.append(f"- **{s['model']}** ({s['adapter']}): {errs or 'no errors'}")
        ar = s["args"]
        lines.append(f"  - arg-level: missing={ar['missing_total']} extra={ar['extra_total']} "
                     f"wrong_value={ar['wrong_value_total']} wrong_date={ar['wrong_date_total']}")
    lines.append("")

    out_path = Path(args.out)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    table_lines = lines[: len(scores) + 4]
    for line in table_lines:
        print(line)
    print(f"\nwrote {out_path}")
    if any(s["adapter"] == "mock" for s in scores):
        print("note: mock rows are pipeline tests, not measured model performance")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
